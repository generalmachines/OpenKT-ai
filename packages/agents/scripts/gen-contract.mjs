// Embeds prompts/*.md and schemas/*.json into src/generated/contract.ts so the
// library has no runtime file access. The .md and .json files stay the source of truth.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["extract", "tag", "dedupe", "route", "write_section", "summarise", "describe_image", "brief"];

const prompts = {};
const schemas = {};
for (const name of names) {
  prompts[name] = readFileSync(join(root, "prompts", `${name}.md`), "utf8").trim();
  schemas[name] = JSON.parse(readFileSync(join(root, "schemas", `${name}.json`), "utf8"));
}

const out = `// GENERATED by scripts/gen-contract.mjs from prompts/*.md and schemas/*.json. Do not edit.
// SPDX-License-Identifier: Apache-2.0
export const AGENT_NAMES = ${JSON.stringify(names)} as const;
export type AgentName = (typeof AGENT_NAMES)[number];

export const PROMPTS: Record<AgentName, string> = ${JSON.stringify(prompts, null, 2)};

export const SCHEMAS: Record<AgentName, Record<string, unknown>> = ${JSON.stringify(schemas, null, 2)};
`;

const target = join(root, "src", "generated", "contract.ts");
mkdirSync(dirname(target), { recursive: true });
let current = "";
try { current = readFileSync(target, "utf8"); } catch {}
if (current !== out) writeFileSync(target, out);
